const DICTS: Record<Lang, Record<Key, string>> = { en, it, es, fr, de };
const DEFAULT_LOCALES: Record<Lang, string> = { en: 'en-GB', it: 'it-IT', es: 'es-ES', fr: 'fr-FR', de: 'de-DE' };
const LANG_KEY = 'spendly.lang';

const isLang = (v: unknown): v is Lang => typeof v === 'string' && v in LANGS;

function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (isLang(saved)) return saved;
  } catch {
    /* storage unavailable */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return 'en';
}

export let lang: Lang = detectLang();

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    /* storage unavailable */
  }
}

/** BCP-47 locale for number/date formatting: keeps the browser's region when it matches the chosen language. */
export function locale(): string {
  const nav = navigator.language ?? '';
  return nav.slice(0, 2).toLowerCase() === lang && nav.length > 2 ? nav : DEFAULT_LOCALES[lang];
}

export function t(key: Key, params?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const countLabel = (n: number): string => (n === 1 ? t('expenseOne') : t('expenseMany', { n }));
